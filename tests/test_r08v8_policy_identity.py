def test_domains_are_separated_and_no_other_identity_accepts_these_families():
    for mod in (v2pi, v3pi, v4pi, v5pi, v6pi):
        for fam, eff in ((ANC, {AF: "anchor"}), (AGE, {GF: 60}), (TOL, {TF: 0})):
            assert code(mod.effective_policy_digest, fam, eff) == ("family_unsupported", "family")
    for fam, eff in ((ANC, {AF: "anchor"}), (AGE, {GF: 60}), (TOL, {TF: 0})):
        assert code(v7.effective_policy_digest, fam, eff) == ("family_unsupported", "family")
    # and v8 refuses every earlier family, including irreversibility
    for fam, eff in (("f5-action-class-irreversibility-policy", {"class_irreversible": {"class-a": "irreversible"}}),
                     ("f5-action-class-revocation-assurance-policy", {"class_requires_revocation_assurance": {"class-a": "required"}}),
                     ("f5-terminal-revocation-enablement-policy", {"terminal_revocation": "on"}),
                     ("f5-action-class-unreadable-policy", {"class_on_unreadable": {"class-a": "refuse"}}),
                     ("f5-action-class-age-bounds", {"class_status_max_age_seconds": {"class-a": 30}})):
        assert code(v8.effective_policy_digest, fam, eff) == ("family_unsupported", "family")
    pre = v8.effective_preimage(AGE, {GF: 60})
    for dom in (b"ocs-reg/r08-v2/effective-policy\n", b"ocs-reg/r08-v3/effective-policy\n", b"ocs-reg/r08-v4/effective-policy\n", b"ocs-reg/r08-v5/effective-policy\n",
                b"ocs-reg/r08-v6/effective-policy\n", b"ocs-reg/r08-v7/effective-policy\n", b"", b"ocs-reg/r08-v8/selection\n"):
        assert independent_digest(pre, dom) != v8.effective_policy_digest(AGE, {GF: 60})


def test_contract_version_dispatch():
    for ver in ("r08-v7", "r08-v6", "r08-v5", "r08-v4", "r08-v3", "r08-v2", "r08-v1", "R08-V8", "", "r08-v8 ", "r08-v9"):
        assert code(v8.effective_policy_digest, AGE, {GF: 60}, ver) == ("contract_unsupported", "contract_version")
    assert code(v8.effective_policy_digest, AGE, {GF: 60}, None) == ("field_type_invalid", "contract_version")
    assert code(v8.effective_policy_digest, AGE, {GF: 60}, b"r08-v8") == ("field_type_invalid", "contract_version")
    assert code(v8.effective_policy_digest, AGE, {GF: 60}, S("r08-v8")) == ("field_type_invalid", "contract_version")
    assert v8.effective_policy_digest(AGE, {GF: 60}, "r08-v8") == v8.effective_policy_digest(AGE, {GF: 60})
    assert code(v8.effective_policy_digest, None, {GF: 60}) == ("field_type_invalid", "family")
    assert code(v8.effective_policy_digest, 5, {GF: 60}) == ("field_type_invalid", "family")
    assert code(v8.effective_policy_digest, S(AGE), {GF: 60}) == ("field_type_invalid", "family")
    assert code(v8.effective_policy_digest, "nope", {GF: 60}) == ("family_unsupported", "family")
    assert code(v7.effective_policy_digest, "f5-action-class-irreversibility-policy", {"class_irreversible": {"class-a": "irreversible"}}, "r08-v8") == (
        "contract_unsupported", "contract_version")


def test_anchor_value_refusals_use_the_existing_scalar_enum_kind():
    assert code(v8.effective_policy_digest, ANC, {}) == ("field_missing", AF)
    assert code(v8.effective_policy_digest, ANC, {AF: "anchor", "zzz": 1}) == ("field_unknown", "zzz")
    assert code(v8.effective_policy_digest, ANC, None) == ("field_type_invalid", None)
    for bad in (True, False, None, 1, 1.0, b"anchor", ["anchor"], {"a": 1}, S("anchor")):
        assert code(v8.effective_policy_digest, ANC, {AF: bad}) == ("field_type_invalid", AF)
    for bad in ("Anchor", "false", "true", "", "anchor ", "no-change", "off"):
        assert code(v8.effective_policy_digest, ANC, {AF: bad}) == ("field_invalid", AF)


@pytest.mark.parametrize("fam,field,lo", [(AGE, GF, 1), (TOL, TF, 0)])
def test_scalar_int_refusals(fam, field, lo):
    assert code(v8.effective_policy_digest, fam, {}) == ("field_missing", field)
    assert code(v8.effective_policy_digest, fam, {field: 5, "zzz": 1}) == ("field_unknown", "zzz")
    assert code(v8.effective_policy_digest, fam, {"clock_tolerance_seconds": 5}) == ("field_missing", field)  # missing is reported before unknown
    assert code(v8.effective_policy_digest, fam, {"clock_tolerance_seconds": 5, field: 5}) == ("field_unknown", "clock_tolerance_seconds")
    assert code(v8.effective_policy_digest, fam, None) == ("field_type_invalid", None)
    assert code(v8.effective_policy_digest, fam, []) == ("field_type_invalid", None)
    for bad in (True, False, None, 1.0, 60.0, "60", "1", "", b"60", [60], {"a": 1}, I(5), float("nan")):
        assert code(v8.effective_policy_digest, fam, {field: bad}) == ("field_type_invalid", field), bad
    for bad in (lo - 1, -1, INT_MAX + 1, 2 ** 31, 2 ** 63, 10 ** 12, 10 ** 30, 10 ** 400):
        assert code(v8.effective_policy_digest, fam, {field: bad}) == ("field_invalid", field), bad
    for ok in (lo, lo + 1, 59, 60, INT_MAX - 1, INT_MAX):
        assert v8.effective_policy_digest(fam, {field: ok}).startswith("sha256:")


