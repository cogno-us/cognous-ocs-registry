"""Effective-policy identity for the `r08-v8` families, including the additive `scalar-int` identity kind (DRAFT / PROPOSED / GATED; BUILDER_TESTED; not independently
qualified).

The digest is recomputed with an independent canonical encoder (not the module's; vectors generated by docs/family-migration/final-three-prep/evidence/genvec8.py), so a
serializer defect cannot hide itself. The preimage carries the INTEGER `family_schema_revision` and never the legacy `family_version` tag.
"""
