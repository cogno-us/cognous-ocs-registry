def test_scalar_int_is_additive_the_existing_kinds_are_unchanged():
    """The classmap-enum and scalar-enum branches of the engine identity are unchanged: v7 and V6_COMPAT digests equal the independent encoder's."""
    eff = {"class_irreversible": {"class-a": "irreversible", "class-b": "no_change"}}
    pre = {"effective_policy_profile": "ocs-effective-policy/1", "contract_version": "r08-v7", "family": "f5-action-class-irreversibility-policy",
           "family_schema_revision": 1, "deny_all": [], "effective": eff}
    assert v7.effective_policy_digest("f5-action-class-irreversibility-policy", eff) == independent_digest(pre, b"ocs-reg/r08-v7/effective-policy\n")
    tr = {"terminal_revocation": "on"}
    pre6 = {"effective_policy_profile": "ocs-effective-policy/1", "contract_version": "r08-v6", "family": "f5-terminal-revocation-enablement-policy",
            "family_version": "v6", "deny_all": [], "effective": tr}
    got = identity_e.effective_policy_digest(profiles.V6_COMPAT, "f5-terminal-revocation-enablement-policy", tr)
    assert got == independent_digest(pre6, b"ocs-reg/r08-v6/effective-policy\n") == v6pi.effective_policy_digest("f5-terminal-revocation-enablement-policy", tr)


