def test_family_and_contract_are_bound_into_the_digest():
    pre = v8.effective_preimage(AGE, {GF: 60})
    d = v8.effective_policy_digest(AGE, {GF: 60})
    assert independent_digest(dict(pre, family=TOL)) != d
    assert independent_digest(dict(pre, contract_version="r08-v7")) != d
    assert independent_digest(dict(pre, deny_all=["x"])) != d
    assert independent_digest(dict(pre, effective_policy_profile="ocs-effective-policy/2")) != d
    assert independent_digest(dict(pre, effective={GF: 61})) != d


